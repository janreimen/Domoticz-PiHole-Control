#!/usr/bin/env python3
"""Generate docs/DEVICES.md from the device model in pihole_control/constants.py.

    python3 tools/gen_device_catalog.py          write docs/DEVICES.md
    python3 tools/gen_device_catalog.py --check  exit 1 when docs/DEVICES.md is stale (the test suite does the same)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pihole_control import constants as c  # noqa: E402

TARGET = os.path.join(ROOT, "docs", "DEVICES.md")

# where each statistics device gets its value from (reply of GET /api/stats/summary)
SOURCES = {
    "dns_queries": "`queries.total`",
    "ads_blocked": "`queries.blocked`",
    "ads_percentage": "`queries.percent_blocked`",
    "domains_blocked": "`gravity.domains_being_blocked`",
    "queries_forwarded": "`queries.forwarded`",
    "queries_cached": "`queries.cached`",
    "clients_ever": "`clients.total`",
    "unique_clients": "`clients.active`",
    "unique_domains": "`queries.unique_domains`",
    "status": "the connection: On while polls succeed, Off while they fail",
}

TYPES = {
    c.KIND_COUNT: "Custom Sensor",
    c.KIND_PERCENT: "Percentage",
    c.KIND_STATUS: "Switch (On/Off), read-only",
}


def render():
    out = [
        "# Devices",
        "",
        "<!-- Generated by tools/gen_device_catalog.py from pihole_control/constants.py. Do not edit by hand: "
        "run the tool. -->",
        "",
        "The plugin creates the devices below. The unit numbers are the ones of the plugin before 0.1.0 and never "
        "change, so an upgrade keeps every device, its history, scenes, scripts and schedules.",
        "",
        "## Statistics (units 1-%d)" % c.UNIT_STATUS,
        "",
        "Created when missing (at start and at every poll), read-only, in use from the start; counters show their unit. "
        "Values come from the reply of `GET /api/stats/summary`.",
        "",
        "| Unit | Name | Type | Unit label | Source |",
        "|---:|---|---|---|---|",
    ]
    for spec in c.STAT_DEVICES:
        label = spec.label or "-"
        out.append("| %d | %s | %s | %s | %s |" % (spec.unit, spec.name, TYPES[spec.kind], label, SOURCES[spec.key]))
    out += [
        "",
        "Unchanged values are rewritten every %d seconds so Domoticz' sensor time-out never marks a quiet sensor "
        "as dead. A value the Pi-hole does not report leaves its device untouched." % c.REFRESH_SECONDS,
        "",
        "## Block lists (units %d-%d)" % (c.LIST_UNIT_FIRST, c.LIST_UNIT_LAST),
        "",
        "One On/Off switch per list of the Pi-hole (block and allow lists). On = the list is enabled.",
        "",
        "| | |",
        "|---|---|",
        "| Name | `%s<comment> (<groups>)`, e.g. `List: Kids - Social Media (Kids)`. Without a comment the list address is "
        "used, without groups the part in brackets is left out |" % c.LIST_NAME_PREFIX,
        "| Description | `%s<id>` (the Pi-hole's id of the list; this is how a device finds its list again) |"
        % c.LIST_PREFIX,
        "| Units | the next free one from %d to %d, so at most %d lists |"
        % (c.LIST_UNIT_FIRST, c.LIST_UNIT_LAST, c.LIST_UNIT_LAST - c.LIST_UNIT_FIRST + 1),
        "",
        "## Groups (units %d-%d)" % (c.GROUP_UNIT_FIRST, c.GROUP_UNIT_LAST),
        "",
        "One On/Off switch per group of the Pi-hole. On = the group is enabled.",
        "",
        "| | |",
        "|---|---|",
        "| Name | `%s<name>`, e.g. `Group: Kids` |" % c.GROUP_NAME_PREFIX,
        "| Description | `%s<id>` |" % c.GROUP_PREFIX,
        "| Units | the next free one from %d to %d, so at most %d groups |"
        % (c.GROUP_UNIT_FIRST, c.GROUP_UNIT_LAST, c.GROUP_UNIT_LAST - c.GROUP_UNIT_FIRST + 1),
        "",
        "## How devices follow the Pi-hole",
        "",
        "- A new list or group gets a device on the next poll.",
        "- A list or group that is gone from the Pi-hole loses its device only after it was missing for %d polls in a "
        "row, so one odd answer can not delete a device and its history." % c.REMOVE_AFTER_MISSES,
        "- A device is renamed when its name changes *in the Pi-hole* while the plugin runs. A name you choose in "
        "Domoticz is never overwritten when the plugin starts.",
        "- Do not edit the **Description** of a list or group device: it is the link to the Pi-hole.",
        "- A device you delete in Domoticz is created again on the next poll (a list or group device: while it exists "
        "in the Pi-hole).",
        "- Every device is created *in use* (visible), so nothing has to be added by hand under Setup > Devices. A counter "
        "that was created without a unit gets its unit at start; a unit or a hidden state you set yourself is never "
        "changed.",
        "- Domoticz refuses new devices while *Setup > Settings > System > Accept new Hardware Devices* is off. The "
        "plugin says so once in the log and asks again every %d minutes (statistics, lists and groups alike), so the "
        "devices appear as soon as the setting is on, without restarting the hardware." % (c.CREATE_RETRY_SECONDS // 60),
        "",
    ]
    return "\n".join(out)


def main(argv):
    text = render()
    if "--check" in argv:
        with open(TARGET, encoding="utf-8") as fh:
            if fh.read() != text:
                print("docs/DEVICES.md is stale: run python3 tools/gen_device_catalog.py", file=sys.stderr)
                return 1
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(TARGET, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
